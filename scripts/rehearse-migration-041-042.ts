type Engine = Awaited<ReturnType<typeof createEngine>>;

const freshDatabase = async (extra = ''): Promise<Engine> => {
  const db = await createEngine();
  await db.exec(
    `CREATE ROLE ${RUNTIME_ROLE};
     CREATE SCHEMA IF NOT EXISTS ${TARGET_SCHEMA} AUTHORIZATION ${RUNTIME_ROLE};`,
  );
  await db.exec(SCHEMA_SQL);
  await db.exec(SEED);
  if (extra) await db.exec(extra);
  return db;
};

const scalar = async (db: Engine, sql: string): Promise<string> => {
  const result: any = await db.query(sql);
  return String(Object.values(result.rows[0] ?? {})[0] ?? '');
};

const failures: string[] = [];

const check = (name: string, condition: boolean, detail = ''): void => {
  if (condition) {
    console.log(`    pass  ${name}`);
  } else {
    console.log(`    FAIL  ${name}${detail ? ` — ${detail}` : ''}`);
    failures.push(name);
  }
};

/** Applies SQL, reporting a throw as a named failure rather than a raw dump. */
const apply = async (db: Engine, sql: string, what: string): Promise<boolean> => {
  try {
    await db.exec(sql);
    return true;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    check(what, false, message.split('\n')[0]);
    return false;
  }
};

async function main(): Promise<void> {
  console.log('\nServana — executed rehearsal of 041 + 042');
  console.log('  EMBEDDED PostgreSQL (PGlite, in-process)\n');

  // ── 041 ────────────────────────────────────────────────────────────────────
  console.log('  041 · Plumbing and Carpentry into Home Maintenance');
  {
    const db = await freshDatabase();
    try {
      check('starts with offerings 2 and 8 mapped to nothing',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.provider_catalog_offering_mappings
                            WHERE offering_id IN (2, 8)`)) === '0');

      if (!(await apply(db, M041, '041 runs'))) return;

      check('offering 2 now maps to family 69',
        (await scalar(db, `SELECT service_id FROM ${TARGET_SCHEMA}.provider_catalog_offering_mappings
                            WHERE offering_id = 2`)) === '69');
      check('offering 8 now maps to family 70',
        (await scalar(db, `SELECT service_id FROM ${TARGET_SCHEMA}.provider_catalog_offering_mappings
                            WHERE offering_id = 8`)) === '70');

      check('both subcategories are under Home Maintenance',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.catalog_subcategories
                            WHERE legacy_service_family_id IN (69,70) AND category_id = 1`)) === '2');

      // The customer-facing promise. An ACTIVE empty section would put
      // "Plumbing (0)" in front of every customer browsing Home Maintenance.
      check('neither is visible to customers yet (draft)',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.catalog_subcategories
                            WHERE legacy_service_family_id IN (69,70) AND status = 'active'`)) === '0');

      check('both families have Metro Manila coverage',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_coverage_geo
                            WHERE service_id IN (69,70) AND radius_km = 50 AND is_active`)) === '2');

      check('nothing new is on sale — no services were invented',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_options
                            WHERE service_id IN (69,70)`)) === '0');
    } finally {
      await db.close();
    }
  }

  {
    const db = await freshDatabase();
    try {
      await db.exec(M041);
      const before = await scalar(db,
        `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.provider_catalog_offering_mappings`);
      await db.exec(M041);
      await db.exec(M041);
      const after = await scalar(db,
        `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.provider_catalog_offering_mappings`);
      check('041 is idempotent over three runs', before === after, `${before} then ${after}`);
    } finally {
      await db.close();
    }
  }

  // ── 042 ────────────────────────────────────────────────────────────────────
  console.log('\n  042 · retire the four duplicates');
  {
    const db = await freshDatabase();
    try {
      if (!(await apply(db, M042, '042 runs'))) return;

      check('all four are retired',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families
                            WHERE id IN (53,54,66,68) AND deleted_at IS NOT NULL`)) === '4');

      check('the families that sell things are untouched',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families
                            WHERE id IN (1,2,67) AND deleted_at IS NULL`)) === '3');

      check('69 and 70 are NOT retired — they are being brought live',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families
                            WHERE id IN (69,70) AND deleted_at IS NULL`)) === '2');

      check('every provider keeps a live family to work through',
        (await scalar(db, `SELECT COUNT(DISTINCT e.employee_uid)
                             FROM ${TARGET_SCHEMA}.employee_services e
                            WHERE e.service_id IN (53,54,66,68)
                              AND NOT EXISTS (SELECT 1 FROM ${TARGET_SCHEMA}.employee_services l
                                              JOIN ${TARGET_SCHEMA}.service_families f ON f.id = l.service_id
                                             WHERE l.employee_uid = e.employee_uid AND f.deleted_at IS NULL)`)) === '0');

      check('nothing is deleted — the rows survive',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families`)) === '9');
    } finally {
      await db.close();
    }
  }

  {
    const db = await freshDatabase();
    try {
      await db.exec(M042);
      const first = await scalar(db,
        `SELECT MAX(deleted_at)::text FROM ${TARGET_SCHEMA}.service_families WHERE id = 53`);
      await db.exec(M042);
      const second = await scalar(db,
        `SELECT MAX(deleted_at)::text FROM ${TARGET_SCHEMA}.service_families WHERE id = 53`);
      check('042 is idempotent', first === second, `${first} then ${second}`);
    } finally {
      await db.close();
    }
  }

  // ── The guard that matters most ────────────────────────────────────────────
  console.log('\n  042 · refuses to retire a family that is no longer empty');
  {
    // A family that has acquired a service since this was written is not a
    // duplicate of anything, and must not be retired by an id that was true
    // last week.
    const db = await freshDatabase(
      `INSERT INTO ${TARGET_SCHEMA}.service_options (service_id, option_type, level_3)
       VALUES (54, 'MAIN', 'Gel Extensions');`,
    );
    try {
      let threw = '';
      try {
        await db.exec(M042);
      } catch (error) {
        threw = error instanceof Error ? error.message : String(error);
      }
      check('a family that gained a service is refused',
        /expected 4/i.test(threw), threw.split('\n')[0] || 'it did not throw');
      check('and nothing was retired',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families
                            WHERE deleted_at IS NOT NULL`)) === '0');
    } finally {
      await db.close();
    }
  }

  {
    // A provider with no live family must block the retirement rather than
    // lose every job they can do.
    const db = await freshDatabase(
      `INSERT INTO ${TARGET_SCHEMA}.employee_services (employee_uid, service_id)
       VALUES ('only-hair', 53);`,
    );
    try {
      let threw = '';
      try {
        await db.exec(M042);
      } catch (error) {
        threw = error instanceof Error ? error.message : String(error);
      }
      check('a provider who would be stranded blocks it',
        /would lose all assignable work/i.test(threw),
        threw.split('\n')[0] || 'it did not throw');
    } finally {
      await db.close();
    }
  }

  // ── Both, in order ─────────────────────────────────────────────────────────
  console.log('\n  041 then 042, as they will be applied');
  {
    const db = await freshDatabase();
    try {
      if (!(await apply(db, M041, '041 runs first'))) return;
      if (!(await apply(db, M042, '042 runs after it'))) return;

      check('four retired, and Plumbing and Carpentry live',
        (await scalar(db, `SELECT COUNT(*) FROM ${TARGET_SCHEMA}.service_families
                            WHERE deleted_at IS NULL`)) === '5');
      check('the survivors are 1, 2, 67, 69, 70',
        (await scalar(db, `SELECT string_agg(id::text, ',' ORDER BY id)
                             FROM ${TARGET_SCHEMA}.service_families WHERE deleted_at IS NULL`))
          === '1,2,67,69,70');
    } finally {
      await db.close();
    }
  }

  console.log(
    `\n  RESULT: ${failures.length === 0 ? 'PASS' : `FAIL — ${failures.join(', ')}`}\n`,
  );
  if (failures.length) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
