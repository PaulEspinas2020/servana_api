/**
 * Execute migrations 041 and 042 on a real PostgreSQL. Nothing else does.
 *
 * Same reason as 039 and 040: `db:verify:embedded` seeds DML-only migrations
 * into its ledger as already applied, so a data migration would otherwise
 * reach production having never run anywhere.
 *
 * They are rehearsed TOGETHER because they are one decision — 041 brings
 * Plumbing and Carpentry live, 042 retires the four duplicates — and because
 * 042's guards read state 041 creates: retiring a family that has just been
 * given an offering mapping must fail, and only running both proves it does.
 *
 * Run: npm run migration:041-042:rehearse
 */

import fs from 'fs';
import path from 'path';

import { createEngine, RUNTIME_ROLE, TARGET_SCHEMA } from './lib/embeddedEngine';

const read = (file: string) =>
  fs.readFileSync(path.resolve(__dirname, 'migrations', file), 'utf8');

const M041 = read('041-home-maintenance-plumbing-carpentry.sql');
const M042 = read('042-retire-duplicate-service-families.sql');

/**
 * The five tables these migrations touch, from `scripts/baseline/000-baseline.sql`.
 *
 * The UNIQUE on `(offering_id, service_id, level_2)` is copied verbatim — it is
 * what makes 041's `ON CONFLICT DO NOTHING` idempotent rather than duplicating,
 * and a simplified table would let the rehearsal pass and production diverge.
 */
const SCHEMA_SQL = `
CREATE TABLE ${TARGET_SCHEMA}.service_families (
  id integer NOT NULL PRIMARY KEY,
  name character varying NOT NULL,
  category character varying,
  created_at timestamptz DEFAULT NOW(),
  deleted_at timestamptz
);

CREATE TABLE ${TARGET_SCHEMA}.service_options (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id integer NOT NULL,
  option_type character varying NOT NULL,
  level_3 character varying,
  is_active boolean DEFAULT true
);

CREATE TABLE ${TARGET_SCHEMA}.catalog_categories (
  id integer NOT NULL PRIMARY KEY,
  name character varying NOT NULL,
  status character varying NOT NULL
    CHECK (status IN ('draft','active','inactive','archived'))
);

CREATE TABLE ${TARGET_SCHEMA}.catalog_subcategories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL,
  name character varying NOT NULL,
  slug character varying,
  display_order integer DEFAULT 0,
  status character varying NOT NULL
    CHECK (status IN ('draft','active','inactive','archived')),
  legacy_service_family_id integer,
  created_at timestamptz DEFAULT NOW(),
  updated_at timestamptz DEFAULT NOW(),
  archived_at timestamptz
);

CREATE TABLE ${TARGET_SCHEMA}.service_coverage_geo (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id integer NOT NULL,
  center_lat numeric NOT NULL,
  center_lon numeric NOT NULL,
  radius_km numeric NOT NULL,
  is_active boolean DEFAULT true
);

CREATE TABLE ${TARGET_SCHEMA}.provider_catalog_offerings (
  id integer NOT NULL PRIMARY KEY,
  name character varying NOT NULL,
  status character varying NOT NULL,
  provider_web_visible boolean NOT NULL DEFAULT true
);

CREATE TABLE ${TARGET_SCHEMA}.provider_catalog_offering_mappings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offering_id integer NOT NULL REFERENCES ${TARGET_SCHEMA}.provider_catalog_offerings(id),
  service_id integer NOT NULL,
  level_2 character varying NOT NULL,
  display_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (offering_id, service_id, level_2)
);

CREATE TABLE ${TARGET_SCHEMA}.employee_services (
  employee_uid text NOT NULL,
  service_id integer NOT NULL
);
`;

