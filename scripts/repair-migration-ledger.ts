/**
 * Repair the CRLF checksums in `servana.schema_migrations`.
 *
 * Run: npm run migrations:ledger:repair        — print the SQL. Connects to nothing.
 *
 * ## What is broken
 *
 * `scripts/lib/migrationChecksum.ts` fixed the hash so it answers "has the
 * CONTENT changed" rather than "which OS wrote this file". That fixed the
 * PRODUCER. It did not fix the 38 rows already in the ledger, which still hold
 * sha256 of CRLF bytes.
 *
 * `run-migrations.ts` reads migrations in order and throws on the FIRST
 * mismatch, so one stale row stops every migration behind it. With 38 stale
 * rows, `migrations:apply` fails at `001-massage-services.sql` and nothing after
 * it can ever run. That is the state today: the code fix landed in d4b0150, the
 * ledger repair did not, and `deploy.yml` runs `migrations:apply` BEFORE the PM2
 * restart specifically so a failing migration stops short of restarting — so a
 * deploy carrying a migration currently fails closed and the old code keeps
 * serving.
 *
 * Migration 036 is the one that matters right now. It owns `booking_evidence`,
 * the runtime DDL that used to create that table has been deleted, and TAB 04's
 * evidence endpoints are specified against it.
 *
 * ## Why this only ever emits UPDATE, never INSERT
 *
 * An UPDATE corrects how an APPLIED migration was recorded. An INSERT would
 * assert that a migration ran when it may not have — and the ledger is the only
 * record of that. A row inserted here would permanently convince every future
 * deploy to skip a migration whose SQL never touched the database, which is a
 * worse and quieter failure than the one being fixed.
 *
 * So: a migration absent from the ledger is PENDING, not damaged. It is left
 * alone, `migrations:apply` will run it once the rows ahead of it stop throwing,
 * and the verification query below reports it rather than repairing it.
 *
 * ## Why the UPDATE is guarded and offline
 *
 * `AND checksum_sha256 <> $new` makes the statement idempotent: re-running it
 * changes nothing, and a row already correct is never rewritten. The whole
 * repair is one transaction, so it either lands completely or not at all.
 *
 * Nothing here connects to a database. The correct checksums are a pure function
 * of files in this repository, so the repair can be reviewed as text, by a
 * person, before anything touches the only database that exists — which is
 * production. Applying it is a separate, human-authorised step, the same rule
 * migration 036's own header states.
 */

import fs from 'fs';
import path from 'path';
// The one rule. A second call site hashing by hand is the same bug wearing a
// different hat, and `tests/migration-checksum.test.ts` asserts none exists.
import { migrationChecksum } from './lib/migrationChecksum';

const migrationsDir = path.resolve(__dirname, 'migrations');

export interface LedgerRepairRow {
  name: string;
  checksum: string;
}

/** Every migration file, in the order `run-migrations.ts` reads them. */
export const ledgerRepairRows = (): LedgerRepairRow[] =>
  fs
    .readdirSync(migrationsDir)
    .filter((name) => /^\d{3}-.+\.sql$/.test(name))
    .sort()
    .map((name) => ({
      name,
      checksum: migrationChecksum(fs.readFileSync(path.join(migrationsDir, name), 'utf8')),
    }));

const sqlLiteral = (value: string): string => `'${value.replace(/'/g, "''")}'`;

export const buildRepairSql = (rows: LedgerRepairRow[]): string => {
  const lines: string[] = [];
  lines.push('-- Servana · schema_migrations checksum repair');
  lines.push('-- Generated by scripts/repair-migration-ledger.ts from the migration files.');
  lines.push('-- Review before running. This is the production database.');
  lines.push('');
  lines.push('-- BEFORE — every row whose recorded checksum disagrees with the file:');
  lines.push('--   SELECT migration_name, checksum_sha256 FROM servana.schema_migrations ORDER BY migration_name;');
  lines.push('');
  lines.push('BEGIN;');
  lines.push('');
  for (const row of rows) {
    lines.push(
      `UPDATE servana.schema_migrations SET checksum_sha256 = ${sqlLiteral(row.checksum)}`,
    );
    lines.push(
      `  WHERE migration_name = ${sqlLiteral(row.name)} AND checksum_sha256 <> ${sqlLiteral(row.checksum)};`,
    );
  }
  lines.push('');
  lines.push('COMMIT;');
  lines.push('');
  lines.push('-- AFTER — migrations present as files but ABSENT from the ledger are');
  lines.push('-- PENDING, not damaged. They are deliberately not inserted here; let');
  lines.push('-- `npm run migrations:apply` run them.');
  lines.push('--   SELECT f.name FROM (VALUES');
  lines.push(
    rows.map((r) => `--     (${sqlLiteral(r.name)})`).join(',\n'),
  );
  lines.push('--   ) AS f(name)');
  lines.push('--   LEFT JOIN servana.schema_migrations m ON m.migration_name = f.name');
  lines.push('--   WHERE m.migration_name IS NULL;');
  return lines.join('\n');
};

if (require.main === module) {
  const rows = ledgerRepairRows();
  process.stdout.write(`${buildRepairSql(rows)}\n`);
  process.stderr.write(
    `\nrepair-migration-ledger: ${rows.length} migration files; ${rows.length} guarded UPDATEs emitted, 0 INSERTs.\n`
    + 'Nothing was connected to. Applying this is a separate, human-authorised step.\n',
  );
}
